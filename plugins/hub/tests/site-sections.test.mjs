import assert from 'node:assert/strict'
import { copyFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { after, test } from 'node:test'
import { PLUGIN, sandbox } from './helper.mjs'

const sb = sandbox()
after(() => sb.cleanup())

const TEMPLATE = join(PLUGIN, 'templates', 'site')
const DOCS = {
  'index.md': '# Home\n\nThe docs.\n',
  'reference/index.md': '# Reference\n\nWhat there is.\n',
  'reference/config.md': '# Config\n\nThe settings.\n',
  'guides/README.md': '---\ntitle: "Guides"\n---\n\nHow to do things.\n',
  'guides/setup.md': '# Setup\n\nSet it up.\n',
  'how-to/run-tests.md': '# Run the tests\n\nRun them.\n',
  'notes/a.md': '# A note\n\nA note.\n',
  '_partials/part.md': 'A part.\n',
  '.hidden/page.md': '# Hidden\n',
  'images/diagram.png': 'not a page',
}

let n = 0
// A site folder with a copy of the helper and its own site.json, next to a docs folder.
async function load(labels = {}) {
  const at = sb.path(`site-${++n}`)
  for (const [p, text] of Object.entries(DOCS)) sb.write(join(at, 'docs', p), text)
  mkdirSync(join(at, 'docs-site'), { recursive: true })
  for (const f of ['sections.js', 'sidebars.js']) copyFileSync(join(TEMPLATE, f), join(at, 'docs-site', f))
  sb.write(join(at, 'docs-site', 'site.json'), JSON.stringify({ title: 'Docs', noIndex: true, labels }))
  delete process.env.DOCS_DIR
  const url = file => pathToFileURL(join(at, 'docs-site', file)).href
  return { sections: await import(url('sections.js')), sidebars: (await import(url('sidebars.js'))).default }
}

test('sections: an index gives the label, README.md counts as one, a folder without one is named after itself (SIT-7, SIT-8)', async () => {
  const { sections, sidebars } = await load()
  assert.deepEqual(
    sections.sections().map(s => [s.id, s.label]),
    [
      ['guides', 'Guides'],
      ['how-to', 'How to'],
      ['notes', 'Notes'],
      ['reference', 'Reference'],
    ],
  )
  assert.deepEqual(Object.keys(sidebars).sort(), ['guides', 'how-to', 'notes', 'reference'])
  assert.deepEqual(sidebars['how-to'], [{ type: 'autogenerated', dirName: 'how-to' }])
})

test('a label in site.json names a folder without an index', async () => {
  const { sections } = await load({ 'how-to': 'Recipes' })
  assert.equal(sections.sections().find(s => s.id === 'how-to').label, 'Recipes')
  assert.equal(sections.sections().find(s => s.id === 'notes').label, 'Notes')
})

test('indexFirst puts index.md or README.md first', async () => {
  const { sections } = await load()
  for (const [dir, index] of [
    ['reference', 'reference/index'],
    ['guides', 'guides/README'],
  ]) {
    const items = [
      { type: 'doc', id: `${dir}/a-page` },
      { type: 'category', label: 'More', items: [] },
      { type: 'doc', id: index },
    ]
    const out = await sections.indexFirst({ defaultSidebarItemsGenerator: async () => items, item: { dirName: dir } })
    assert.deepEqual(
      out.map(i => i.id ?? i.label),
      [index, `${dir}/a-page`, 'More'],
    )
  }
})
